-- events: integer identity whose sequence is ~5,000 values from the int4 maximum (2,147,483,647).
SET ROLE migrator;
CREATE TABLE events(
  id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id bigint NOT NULL,
  kind text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now());
INSERT INTO events(id, order_id, kind)
SELECT 2147483647 - 5000 - 2000000 + g, (g % 5000000) + 1, 'seed' FROM generate_series(1, 2000000) g;
SELECT setval(pg_get_serial_sequence('events', 'id'), 2147483647 - 5000);
ALTER TABLE events SET (autovacuum_enabled = off);
GRANT SELECT, INSERT ON events TO app;
GRANT USAGE ON SEQUENCE events_id_seq TO app;
GRANT SELECT ON events TO analytics;
RESET ROLE;
VACUUM ANALYZE events;
-- Fingerprint of existing ids, stored where the migrator cannot write.
CREATE SCHEMA grader AUTHORIZATION postgres;
REVOKE ALL ON SCHEMA grader FROM PUBLIC;
CREATE TABLE grader.events_fp AS SELECT count(*) AS n, sum(id::bigint) AS s FROM events;
