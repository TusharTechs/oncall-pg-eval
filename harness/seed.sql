-- Builds the template database `seed` (cloned per trial with STRATEGY FILE_COPY).
-- Run as superuser. Objects are owned by `migrator`.
DROP DATABASE IF EXISTS seed;
CREATE DATABASE seed OWNER postgres;
\c seed
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
GRANT USAGE, CREATE ON SCHEMA public TO migrator;
SET ROLE migrator;
CREATE TABLE customers(id bigint PRIMARY KEY, name text NOT NULL);
INSERT INTO customers SELECT g, 'c'||g FROM generate_series(1,200000) g;
CREATE TABLE orders(
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id bigint,
  external_ref text,
  qty int NOT NULL,
  status text NOT NULL,
  amount numeric(12,2) NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now());
INSERT INTO orders(id, customer_id, external_ref, qty, status, amount, created_at)
SELECT g, (g % 200000)+1, 'ext-'||g, g%7, 'new', ((g%500)+1) + (g%100)/100.0, now() - (g||' seconds')::interval
FROM generate_series(1,5000000) g;
SELECT setval(pg_get_serial_sequence('orders','id'), 5000000);
-- Autovacuum is disabled on the hot tables so that a background autovacuum can never
-- randomly block (or be blocked by) the migration. This is stated in every ticket.
ALTER TABLE orders SET (autovacuum_enabled = off);
ALTER TABLE customers SET (autovacuum_enabled = off);
GRANT SELECT, INSERT, UPDATE ON orders, customers TO app;
GRANT USAGE ON ALL SEQUENCES IN SCHEMA public TO app;
GRANT SELECT ON orders, customers TO analytics;
RESET ROLE;
GRANT CONNECT ON DATABASE seed TO app, analytics, migrator;
VACUUM ANALYZE orders; VACUUM ANALYZE customers;
